#!/usr/bin/env python3
"""Draw the app icon from the design tokens.

Writes assets/icon.svg, icon.png (the window icon), icon.ico (Windows) and
icon.icns (macOS). The colours are the light theme's, resolved from
assets/tokens.css (DESIGN.md §9: a standalone export takes the light values,
never typed in). Needs Pillow:  pip install pillow && python3 scripts/make_icon.py

The picture is the Breakeven mark: an equity bar, inked in --mark, that runs
past the break-even tick. The window header draws the same thing (draw_mark).
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from breakeven import load_theme  # noqa: E402

from PIL import Image, ImageDraw  # noqa: E402

T = load_theme(dark=False)
TILE, TRACK, FILL, TICK = T["ink"], T["n-700"], T["mark"], T["on-dark"]

# In a 64-unit square, matching draw_mark(): bar 30% of the mark's height,
# filled to 70% of its width, tick at 55%.
MX, MY, MW, MH = 12, 20, 40, 24
BAR_H = MH * 0.3
BY = MY + (MH - BAR_H) / 2
TX, TW = MX + MW * 0.55, MH * 0.14
SHAPES = [
    ("tile", 0, 0, 64, 64, 14, TILE),
    ("track", MX, BY, MX + MW, BY + BAR_H, 0, TRACK),
    ("fill", MX, BY, MX + MW * 0.7, BY + BAR_H, 0, FILL),
    ("tick", TX - TW / 2, MY, TX + TW / 2, MY + MH, 0, TICK),
]


def svg():
    rects = "\n".join(
        f'  <rect x="{x1:g}" y="{y1:g}" width="{x2 - x1:g}" height="{y2 - y1:g}"'
        + (f' rx="{r}"' if r else "") + f' fill="{c}"/>  <!-- {name} -->'
        for name, x1, y1, x2, y2, r, c in SHAPES)
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="64" height="64">\n'
            "  <!-- Generated by scripts/make_icon.py from assets/tokens.css. Don't edit by hand. -->\n"
            f"{rects}\n</svg>\n")


def raster(size):
    big = size * 4                       # draw large, then shrink, for smooth edges
    k = big / 64
    im = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    for _name, x1, y1, x2, y2, r, c in SHAPES:
        box = [round(x1 * k), round(y1 * k), round(x2 * k) - 1, round(y2 * k) - 1]
        if r:
            d.rounded_rectangle(box, radius=r * k, fill=c)
        else:
            d.rectangle(box, fill=c)
    return im.resize((size, size), Image.LANCZOS)


def main():
    out = ROOT / "assets"
    (out / "icon.svg").write_text(svg(), "utf-8")
    raster(256).save(out / "icon.png")
    raster(256).save(out / "icon.ico", sizes=[(s, s) for s in (16, 24, 32, 48, 64, 128, 256)])
    raster(1024).save(out / "icon.icns")
    print("Wrote icon.svg, icon.png, icon.ico, icon.icns to", out)


if __name__ == "__main__":
    main()
